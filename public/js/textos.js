/** Texto en el idioma elegido, con huecos {x}. Si falta, cae al castellano. */
export function texto(lang, clave, vars = {}) {
  const s = T[lang]?.[clave] ?? T.es[clave] ?? clave;
  return String(s).replace(/\{(\w+)\}/g, (_, k) => vars[k] ?? '');
}

